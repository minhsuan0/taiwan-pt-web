  // 僅當提問包含特定的西醫處置、藥物、打針、開刀手術等強烈個別化醫療意圖時，才繞過快取交由 AI 精準對話
  const isMedicalProcedureIntent = /吃藥|藥物|普拿疼|消炎藥|止痛藥|打針|類固醇|增生療法|prp|開刀|手術|照x光|mri|核磁共振|看哪科|掛哪科/i.test(q);
  if (isMedicalProcedureIntent) return null;

