// ─── 2. 執行期記憶體動態快取 (LRU Cache) ──────────────────────────
const dynamicCache = new Map();
const DYNAMIC_TTL = 24 * 60 * 60 * 1000;
const MAX_CACHE_SIZE = 150;

function cleanExpiredCache() {
  const now = Date.now();
  for (const [key, val] of dynamicCache.entries()) {
    if (now > val.expireAt) {
      dynamicCache.delete(key);
    }
  }
  if (dynamicCache.size > MAX_CACHE_SIZE) {
    const oldestKey = dynamicCache.keys().next().value;
    dynamicCache.delete(oldestKey);
  }
}

